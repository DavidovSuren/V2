// ForUser — цитата дня для пользователя: из направления сегодняшнего
// задания (иначе общая). Индекс — хеш от tgID и даты, так что у каждого своя,
// каждый день новая и не меняется при обновлении страницы.
func ForUser(tgID, date, category string) string {
	pool, ok := byCategory[category]
	if !ok {
		pool = general
	}
	h := fnv.New32a()
	h.Write([]byte(tgID + "|" + date))
	return pool[int(h.Sum32()%uint32(len(pool)))]
}
