function slug(category) {
  const map = {
    'Внешность': 'appearance', 'Стиль': 'style', 'Тело': 'body', 'Деньги': 'money',
    'Отношения': 'relationships', 'Окружение': 'environment', 'Карьера': 'career', 'Образ жизни': 'lifestyle'
  };
  return map[category];
}

function toTasks(category, texts, genderTag, prefix) {
  return texts.map((text, i) => ({
    id: `${prefix}-${slug(category)}-${String(i + 1).padStart(3, '0')}`,
    category,
    gender: genderTag,
    text,
    why: CATEGORY_WHY[category]
  }));
}

function buildBank(bodyArray, genderTag) {
  const tasks = [];
  for (const [category, texts] of Object.entries(SHARED_CATEGORIES)) {
    tasks.push(...toTasks(category, texts, 'both', genderTag));
  }
  tasks.push(...toTasks('Тело', bodyArray, genderTag, genderTag));
  return tasks;
}

const maleBank = buildBank(BODY_MALE, 'male');
const femaleBank = buildBank(BODY_FEMALE, 'female');

function validate(bank, label) {
  if (bank.length !== 365) {
    throw new Error(`${label}: ожидалось 365 заданий, получено ${bank.length}`);
  }
  const ids = new Set(bank.map(t => t.id));
  if (ids.size !== bank.length) {
    throw new Error(`${label}: обнаружены дублирующиеся id`);
  }
  if (label === 'female' && bank.some(t => t.text.toLowerCase().includes('отжим'))) {
    throw new Error('female: в женском банке не должно быть заданий с отжиманиями');
  }
}

