#!/bin/sh
# Простой автоперезапуск: если node server.js упадёт (в т.ч. из-за редкого
# нативного краша better-sqlite3), сервер поднимется заново через секунду
# вместо того, чтобы простаивать до ручного вмешательства.
cd "$(dirname "$0")/.."
while true; do
  node server.js
  echo "[supervisor] сервер завершился (код $?), перезапуск через 1с..."
  sleep 1
done
